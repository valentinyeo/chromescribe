import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
const require = createRequire(execSync('npm root -g').toString().trim() + '/');
const { chromium } = require('playwright');
const [path = '/', name = 'home', width = '390', height = '844'] = process.argv.slice(2);
const run = process.env.CS_VERIFY_DIR || '/tmp/cs-verify';
const port = readFileSync(`${run}/port`, 'utf8').trim();
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: Number(width), height: Number(height) } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
const api = [];
page.on('response', (r) => { if (r.url().includes('/api/')) api.push(`${r.status()} ${r.request().method()} ${new URL(r.url()).pathname}`); });
await page.goto(`http://127.0.0.1:${port}${path}`, { waitUntil: 'networkidle' });
const file = `${run}/proof/${name}-${width}.png`;
await page.screenshot({ path: file });
console.log(JSON.stringify({ file, title: await page.title(), api, errors }, null, 1));
await browser.close();
